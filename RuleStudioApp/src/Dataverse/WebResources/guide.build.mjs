// Builds the Documentation page (src/html/guide/index.html) from docs/user-guide.md.
// Run after the guide changes:  node guide.build.mjs ["path/to/user-guide.md"]
// Supports the Markdown the doc uses: headings, paragraphs, nested "-" lists, numbered lists, tables, **bold**, `code`, links.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = process.argv[2] ?? fileURLToPath(new URL("../../../docs/user-guide.md", import.meta.url));
const target = fileURLToPath(new URL("src/html/guide/index.html", import.meta.url));

const escape = (text) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const inline = (text) => escape(text)
  .replace(/`([^`]+)`/g, "<code>$1</code>")
  .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
  .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2" target="_blank" rel="noopener">$1</a>')
  .replace(/\\([_*[\]#|])/g, "$1");
const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const lines = readFileSync(source, "utf8").replace(/\r/g, "").split("\n");
const sections = [];
let html = [];
let i = 0;

function list(indent) {
  const out = [];
  while (i < lines.length) {
    const m = /^( *)- (.*)$/.exec(lines[i]);
    if (!m || m[1].length < indent) break;
    if (m[1].length > indent) { out.push(list(m[1].length)); continue; }
    out.push(`<li>${inline(m[2])}`);
    i++;
    if (i < lines.length && /^( *)- /.exec(lines[i])?.[1].length > indent) out.push(list(/^( *)/.exec(lines[i])[1].length));
    out.push("</li>");
  }
  return `<ul>${out.join("")}</ul>`;
}

function table() {
  const rows = [];
  while (i < lines.length && lines[i].startsWith("|")) rows.push(lines[i++]);
  const cells = (row) => row.replace(/^\||\|$/g, "").split("|").map((c) => inline(c.trim()));
  const [head, , ...body] = rows;
  return `<div class="table-scroll"><table class="data-table"><thead><tr>${cells(head).map((c) => `<th>${c}</th>`).join("")}</tr></thead>`
    + `<tbody>${body.map((r) => `<tr>${cells(r).map((c) => `<td>${c}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`;
}

function flush() {
  if (sections.length) sections[sections.length - 1].body = html.join("\n");
  html = [];
}

let intro = "";
while (i < lines.length) {
  const line = lines[i];
  if (line.startsWith("# ") || /^\w{3} \d+, \d{4} · /.test(line) || !line.trim()) { i++; continue; }
  const h2 = /^## (.*)$/.exec(line);
  const h3 = /^### (.*)$/.exec(line);
  if (h2) { flush(); sections.push({ title: h2[1], id: slug(h2[1]) }); i++; }
  else if (h3) { html.push(`<h3>${inline(h3[1])}</h3>`); i++; }
  else if (/^ *- /.test(line)) html.push(list(/^( *)/.exec(line)[1].length));
  else if (line.startsWith("|")) html.push(table());
  else if (/^\d+\. /.test(line)) {
    const items = [];
    while (i < lines.length && /^\d+\. /.test(lines[i])) items.push(`<li>${inline(lines[i++].replace(/^\d+\. /, ""))}</li>`);
    html.push(`<ol>${items.join("")}</ol>`);
  }
  else if (!sections.length) { intro += inline(line); i++; }
  else { html.push(`<p>${inline(line)}</p>`); i++; }
}
flush();

const toc = sections.map((s) => `<li><a href="#${s.id}">${inline(s.title)}</a></li>`).join("");
const cards = sections.map((s) => `<section class="card doc-section" id="${s.id}">
  <div class="card-head"><h2 class="h3">${inline(s.title)}</h2></div>
  <div class="card-body doc-body">
${s.body}
  </div>
</section>`).join("\n");

writeFileSync(target, `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Documentation · Rule Studio</title>
<!--STYLE-->
</head>
<body>
<!-- Generated by guide.build.mjs from docs/user-guide.md. Do not edit by hand. -->
<main class="workspace">
<div class="rs-commandbar" role="toolbar" aria-label="Documentation commands">
  <button type="button" class="btn cmd-back" id="cmdBack" aria-label="Back" title="Back">←</button>
</div>
<div class="rs-pagehead"><h1>Documentation</h1><p class="rs-desc">${intro}</p></div>
<div class="doc-layout">
<nav class="card doc-toc" aria-label="Contents">
  <div class="card-head"><h2 class="h3">Contents</h2></div>
  <ol>${toc}</ol>
</nav>
<div class="doc-sections">
${cards}
</div>
</div>
</main>
<!--SCRIPT-->
</body>
</html>
`);
console.log(`[guide] ${sections.length} sections → ${target}`);
